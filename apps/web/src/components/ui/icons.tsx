import type { ReactNode, SVGProps } from "react";

// Small line icons drawn inline: no icon library to load. They take the text
// color (currentColor) and are hidden from screen readers: the text next to
// them carries the meaning.

type IconProps = SVGProps<SVGSVGElement>;

function Icon({ children, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      className="size-4 shrink-0"
      {...props}
    >
      {children}
    </svg>
  );
}

